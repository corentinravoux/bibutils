// existing collections, keyed by full path
function pathMap() {
  const all = Zotero.Collections.getByLibrary(LIB, true);
  const byID = {};
  all.forEach(c => byID[c.id] = c);
  const map = {};
  for (const c of all) {
    let parts = [c.name], p = c.parentID;
    while (p) { parts.unshift(byID[p].name); p = byID[p].parentID; }
    map[parts.join("/")] = c;
  }
  return map;
}


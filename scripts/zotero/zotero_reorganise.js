let map = pathMap();
let created = 0;
for (const path of PAYLOAD.paths) {
  if (map[path]) continue;
  const parts = path.split("/");
  const name = parts.pop();
  const parentPath = parts.join("/");
  log((DRY_RUN ? "would create  " : "creating      ") + path);
  created++;
  if (!DRY_RUN) {
    const c = new Zotero.Collection();
    c.libraryID = LIB;
    c.name = name;
    if (parentPath) {
      if (!map[parentPath]) throw new Error("missing parent " + parentPath);
      c.parentID = map[parentPath].id;
    }
    await c.saveTx();
    map = pathMap();
  }
}


let moved = 0, already = 0, missing = 0;
if (!DRY_RUN) map = pathMap();
for (const [key, path] of Object.entries(PAYLOAD.assign)) {
  const id = Zotero.Items.getIDFromLibraryAndKey(LIB, key);
  if (!id) { missing++; log("MISSING ITEM " + key); continue; }
  const item = Zotero.Items.get(id);
  const target = map[path];
  if (!target) { if (DRY_RUN) { moved++; continue; } throw new Error("no collection " + path); }
  const current = item.getCollections();
  if (current.length === 1 && current[0] === target.id) { already++; continue; }
  moved++;
  if (!DRY_RUN) {
    item.addToCollection(target.id);
    if (REMOVE_OLD) for (const cid of current) if (cid !== target.id) item.removeFromCollection(cid);
    await item.saveTx();
  }
}

// --------------------------------------------------- 3. empty old shells
let empties = [];
map = pathMap();
for (const [path, c] of Object.entries(map)) {
  if (PAYLOAD.paths.includes(path)) continue;
  if (c.getChildItems(true).length === 0 && c.getChildCollections(true).length === 0) {
    empties.push(path);
    if (DELETE_EMPTIED && !DRY_RUN) await c.eraseTx();
  }
}

log("");
log("collections created : " + created);
log("items refiled       : " + moved);
log("already correct     : " + already);
log("items not found     : " + missing);
log("old shells now empty: " + empties.length + (empties.length ? "  -> " + empties.join(", ") : ""));
log(DRY_RUN ? "\nDRY RUN -- nothing was written." : "\nApplied.");
return out.join("\n");
